4. 不要改其他任何檔案。
5. 寫完跑 ~/speak-tw/bin/speak-tw 審稿/修稿/$s.md，把抓到的問題改掉（唱句與〈天烏烏〉除外）。
6. 最後回報：每條必修的 id，改成什麼或為什麼不改（一行一條）。" < /dev/null > 審稿/修稿/$s.log2 2>&1
echo "$s done rc=$? $(test -s 審稿/修稿/$s.md && echo out-ok || echo NO-OUT)"
