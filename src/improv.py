def bible(name, only=None):
    if not BIBLE.exists():
        return ''
    m = re.search(rf'^## {name}.*?(?=^## |\Z)', BIBLE.read_text(encoding='utf-8'), re.S | re.M)
    if not m:
        return ''
    t = m.group(0)
    if only:   # 只取指定的小節（余靜不能讀到病的部分）
        parts = re.split(r'(?=^### )', t, flags=re.M)
        t = '\n'.join(p for p in parts if any(o in p.split('\n')[0] for o in only))
    return '\n\n【編劇對這個人的細部描寫】\n' + t


