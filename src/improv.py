def ask(model, p):
    """deepseek-v4.1-flash:1017 走 llmshare（目前閘道只開這一個，不去繞過限制）；'gemini' 走作者自架的 gemini-web（.11）當第二個模型家族"""
    if model == 'gemini':
        import json, ssl, urllib.request
        req = urllib.request.Request('https://192.168.11.11/gemini-web/api/chat', json.dumps({'prompt': p}).encode(),
                                     {'Content-Type': 'application/json', 'x-goog-api-key': _gkey()})
        try:
            return json.load(urllib.request.urlopen(req, timeout=240, context=ssl._create_unverified_context())).get('text', '').strip()
        except Exception as e:  # noqa: BLE001
            print('gemini 例外', repr(e)[:80], flush=True); return ''
    return subprocess.run(['llmshare', 'raw', model, p], capture_output=True, text=True, timeout=240).stdout.strip()


def parse(t):
    g = lambda k: (re.search(rf'^{k}：(.*)$', t, re.M) or [None, ''])[1].strip()
    act, say, thought = g('動作').strip('（）()').strip(), g('台詞'), g('心').strip('（）()').strip()
    m = re.match(r'^[（(]([^）)]*)[）)](.*)$', say)   # gemini 常把動作括號塞在台詞前面
    while m:
        act = act or m.group(1).strip(); say = m.group(2).strip(); m = re.match(r'^[（(]([^）)]*)[）)](.*)$', say)
    say = re.sub(r'[（(][^）)]*[）)]', '', say).strip().strip('「」"“”').strip()
    return act, say, thought


def bad(who, blob):
    if any(b in blob for b in BANNED) or SIMP & set(blob) or any(re.search(p, blob) for p, _ in HARD):
        return True
    return who == '程希' and any(b in blob for b in LEAK)


def turn(who, model, sc, public, mine):
    for _ in range(3):
        act, say, thought = parse(ask(model, prompt(who, sc, public, mine)))
        if say and not bad(who, say + thought + act):
            return act, say, thought
    return act, say, '（檢查沒過，保留）' + thought


def take(scene, k):
    sc = SCENES[scene]; models = MODELS[k % len(MODELS)]; lines, public = [], ''
    mine = {w: '' for w in sc['order']}
    for who in sc['order']:
        act, say, thought = turn(who, model_for(who, models, k), sc, public, mine[who])
        row = ([f'旁白：{act}'] if act else []) + [f'{who}：{say}']
        lines += row + ([f'{who}（心）：{thought}'] if thought else [])
        public += '\n'.join(row) + '\n'   # 別人看得到動作與台詞，看不到（心）
        if thought: mine[who] += f'- {thought}\n'
    OUT.mkdir(exist_ok=True)
    head = f'# {scene} take {k + 1}（{"、".join(f"{w}={model_for(w, models, k)}" for w in dict.fromkeys(sc["order"]))}）\n\n'
    (OUT / f'{scene}-{k + 1}.md').write_text(head + '\n'.join(lines) + '\n', encoding='utf-8')
    return OUT / f'{scene}-{k + 1}.md'


